import {readFile,mkdir,writeFile,cp} from 'node:fs/promises';
import {Marked} from 'marked';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>readFile(path.join(root,p),'utf8');
const escape=s=>String(s).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const markdown=new Marked({gfm:true});
// Repository-authored Markdown is compiled at build time, never in a visitor's browser.
const config=JSON.parse(await read('site.json'));
const slots=Object.fromEntries(Object.entries(config).map(([k,v])=>[k,escape(v)]));
for(const name of ['about','research-summary','publications','project-sentiment-analysis','project-measurement-matcher','contact'])slots[name]=markdown.parse(await read(`content/${name}.md`));
slots.year=String(new Date().getUTCFullYear());
const html=(await read('template.html')).replace(/\{\{([\w-]+)\}\}/g,(_,key)=>{if(!(key in slots))throw new Error(`Unknown template field: ${key}`);return slots[key]});
if((html.match(/<h1[ >]/g)||[]).length!==1)throw new Error('The about file must contain the only # heading; use ## or ### elsewhere.');
await mkdir(path.join(root,'dist'),{recursive:true});
await writeFile(path.join(root,'dist/index.html'),html);
await cp(path.join(root,'assets'),path.join(root,'dist/assets'),{recursive:true});
await cp(path.join(root,'style.css'),path.join(root,'dist/style.css'));
await writeFile(path.join(root,'dist/.nojekyll'),'');
await writeFile(path.join(root,'dist/robots.txt'),`User-agent: *\nAllow: /\nSitemap: ${config.url}/sitemap.xml\n`);
await writeFile(path.join(root,'dist/sitemap.xml'),`<?xml version="1.0" encoding="UTF-8"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"><url><loc>${escape(config.url)}/</loc></url></urlset>`);
console.log('Built portfolio in dist/');
